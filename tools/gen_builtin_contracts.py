#!/usr/bin/env python3
"""Generate immutable discovery tables from the reviewed builtin surface.

No capability is inferred from a flag-shaped string in C. A qualified mode
must identify its operations, checked schema/transport, limits and semantic
gates. CI checks generated files and runs the declared gates separately.
"""
import argparse
import json
from pathlib import Path
import re
import sys
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'schemas/BUILTIN_CONTRACTS.json'
ROLES = {'structured': 'STRUCTURED', 'execution-envelope': 'EXECUTION_ENVELOPE',
         'interactive': 'INTERACTIVE'}
OUTPUTS = {'none', 'native', 'alternate', 'module'}


def schema_reference_node(reference, schemas):
    """Resolve a local schema ID and optional URI-fragment JSON Pointer."""
    if not isinstance(reference, str) or not reference:
        raise ValueError('schema reference must be a nonempty string')
    identifier, separator, fragment = reference.partition('#')
    if identifier not in schemas:
        raise ValueError('unknown schema identifier: ' + identifier)
    node = schemas[identifier]
    if separator and fragment:
        if re.search(r'%(?![0-9A-Fa-f]{2})', fragment):
            raise ValueError('invalid URI fragment escape')
        try:
            pointer = unquote(fragment, encoding='utf-8', errors='strict')
        except UnicodeDecodeError as error:
            raise ValueError('invalid URI fragment UTF-8') from error
        if not pointer.startswith('/'):
            raise ValueError('schema fragment must be a JSON Pointer')
        for encoded in pointer[1:].split('/'):
            if re.search(r'~(?:[^01]|$)', encoded):
                raise ValueError('invalid JSON Pointer escape')
            key = encoded.replace('~1', '/').replace('~0', '~')
            if isinstance(node, dict) and key in node:
                node = node[key]
            elif isinstance(node, list) and re.fullmatch(r'0|[1-9][0-9]*', key):
                try:
                    index = int(key)
                    node = node[index]
                except (ValueError, IndexError) as error:
                    raise ValueError('JSON Pointer array index is unavailable') from error
            else:
                raise ValueError('JSON Pointer target is unavailable')
    if not isinstance(node, (dict, bool)):
        raise ValueError('JSON Pointer target is not a schema object or Boolean')
    return node


def generate(document):
    # C99 only guarantees 4095 bytes in a string literal, including adjacent
    # literal concatenation. Preserve larger reviewed descriptors verbatim in
    # immutable byte arrays instead of truncating them or weakening -Werror.
    long_literals = {}

    def literal(value):
        if value is None:
            return 'NULL'
        raw = value.encode('utf-8')
        if len(raw) <= 4095:
            return json.dumps(value, ensure_ascii=False)
        if raw not in long_literals:
            long_literals[raw] = 'JASH_BUILTIN_CONTRACT_TEXT_' + str(len(long_literals))
        return '(const char*)' + long_literals[raw]

    def encoded(value):
        return literal(None if value is None else json.dumps(value, ensure_ascii=False, separators=(',', ':')))

    if document.get('version') != 1 or document.get('target') != 'linux':
        raise ValueError('unsupported manifest version or qualification target')
    builtins = document['builtins']
    names = [row['name'] for row in builtins]
    if names != sorted(set(names)):
        raise ValueError('builtin names must be unique and sorted')
    catalog = ['/* SPDX-License-Identifier: LicenseRef-SPL-1.0',
               ' * Generated by tools/gen_builtin_contracts.py; edit schemas/BUILTIN_CONTRACTS.json. */',
               '#define JASH_BUILTIN_DENOMINATOR_FROZEN ' + str(int(document['denominator_frozen'])),
               'static const jash_builtin_contract_t BUILTIN_CONTRACTS[] = {']
    modes = ['/* SPDX-License-Identifier: LicenseRef-SPL-1.0',
             ' * Generated by tools/gen_builtin_contracts.py; reviewed operations, never inferred flags. */',
             'static const jash_builtin_mode_contract_t BUILTIN_MODE_CONTRACTS[] = {']
    known_schemas = {}
    for path in (ROOT / 'schemas').glob('*.schema.json'):
        schema = json.loads(path.read_text())
        if '$id' in schema:
            if schema['$id'] in known_schemas:
                raise ValueError('duplicate schema identifier: ' + schema['$id'])
            known_schemas[schema['$id']] = schema
    for row in builtins:
        name = row['name']
        if row['role'] not in ROLES or not (ROOT / row['source']).is_file():
            raise ValueError('invalid role/source: ' + name)
        if row['json_output'] not in OUTPUTS or row['data_output'] not in OUTPUTS:
            raise ValueError('invalid output implementation: ' + name)
        if row['alias_of'] and row['alias_of'].split()[0] not in names:
            raise ValueError('alias target missing: ' + name)
        if row['role'] != 'structured' and row['modes']:
            raise ValueError('non-structured name has a mode: ' + name)
        exclusions = row.get('operation_exclusions', [])
        for excluded in exclusions:
            if (set(excluded) != {'grammar', 'disposition', 'reason'} or
                excluded['disposition'] not in ('execution-envelope', 'interactive', 'external-fallback', 'unimplemented', 'presentation-only') or
                not excluded['grammar'] or not excluded['reason']):
                raise ValueError('invalid operation exclusion: ' + name)
        catalog.append('    { ' + ', '.join([literal(name), literal(row['alias_of']), literal(row['source']),
            'JASH_CONTRACT_' + ROLES[row['role']], 'JASH_CONTRACT_OUTPUT_' + row['json_output'].upper(),
            'JASH_CONTRACT_OUTPUT_' + row['data_output'].upper(), str(int(row['operations_complete'])), encoded(exclusions),
            encoded(row.get('legacy_output_compatibility', []))]) + ' },')
        identities = set()
        for mode in row['modes']:
            identity = (mode['mode'], mode['id'])
            if identity in identities or mode['mode'] not in ('json', 'data'):
                raise ValueError('invalid/duplicate mode: ' + name + ' ' + str(identity))
            identities.add(identity)
            if mode['framing'] not in ('json', 'jsonl', 'jtv1', 'jtv2'):
                raise ValueError('invalid framing: ' + name)
            for field in ('result_schema', 'error_schema'):
                if mode[field] is not None and mode[field] not in known_schemas:
                    raise ValueError('unresolved schema for ' + name + ': ' + mode[field])
            if mode['framing'].startswith('jtv') and mode['result_schema'] is not None:
                raise ValueError('JTV uses in-band JSC, not a JSON schema: ' + name)
            projection = mode['resource_limits'].get('projection_schema')
            if projection is not None:
                try:
                    schema_reference_node(projection, known_schemas)
                except ValueError as error:
                    raise ValueError('unresolved projection schema for ' + name + '/' +
                                     mode['id'] + ': ' + str(projection) + ': ' + str(error)) from error
            for test in mode['semantic_tests']:
                if not test.startswith('tests/') or not (ROOT / test.split('::')[0]).is_file():
                    raise ValueError('semantic gate missing: ' + test)
            if mode['qualified']:
                if not mode['operations'] or not mode['semantic_tests'] or not mode['resource_limits']:
                    raise ValueError('qualification needs operations, gates and bounds: ' + name)
                if mode['framing'] in ('json', 'jsonl') and mode['result_schema'] is None:
                    raise ValueError('qualified JSON mode lacks a schema: ' + name)
                if mode['qualification_scope'] != ['linux']:
                    raise ValueError('only Linux has been qualified in this roadmap: ' + name)
            for operation in mode['operations']:
                if (not operation.get('grammar') or
                    operation.get('effect') not in ('read', 'mutate', 'exec')):
                    raise ValueError('operation needs nonempty grammar and an explicit effect: ' + name)
            if mode['options_complete'] and mode['options'] is None:
                raise ValueError('complete options must be an explicit list: ' + name)
            values = [literal(name)] + [literal(mode[key]) for key in
                ('id', 'mode', 'selector', 'selector_scope', 'framing', 'result_schema')]
            values += [encoded(mode['options'])] + [literal(mode[key]) for key in
                ('error_policy', 'notes', 'error_schema', 'input_framing')]
            values += [encoded(mode['resource_limits']), encoded(mode['operations']),
                       encoded(mode['semantic_tests']), encoded(mode['qualification_scope']),
                       str(int(mode['qualified'])), str(int(mode['options_complete']))]
            modes.append('    { ' + ', '.join(values) + ' },')
        if document['denominator_frozen'] and row['role'] == 'structured' and not row['operations_complete']:
            raise ValueError('cannot freeze an incomplete operation inventory: ' + name)
    catalog.append('};'); modes.append('};')
    strings = ['/* SPDX-License-Identifier: LicenseRef-SPL-1.0',
               ' * Generated by tools/gen_builtin_contracts.py; exact UTF-8 bytes and terminating NUL. */']
    for raw, name in long_literals.items():
        strings.append('static const unsigned char ' + name + '[] = {')
        payload = raw + b'\0'
        for offset in range(0, len(payload), 24):
            strings.append('    ' + ','.join('0x%02x' % byte for byte in payload[offset:offset+24]) + ',')
        strings.append('};')
    return {'c/core/builtin_contract_strings.inc': '\n'.join(strings) + '\n',
            'c/core/builtin_contract_catalog.inc': '\n'.join(catalog) + '\n',
            'c/core/builtin_mode_contracts.inc': '\n'.join(modes) + '\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = generate(json.loads(SOURCE.read_text()))
    stale = []
    for relative, expected in outputs.items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text() != expected:
                stale.append(relative)
        else:
            path.write_text(expected)
    if stale:
        print('Stale builtin contracts: ' + ', '.join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
